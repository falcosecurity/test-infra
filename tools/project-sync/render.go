const generatedMD = "<!-- AUTOGENERATED - DO NOT EDIT this section. Source: falcosecurity/.project; generator: test-infra/tools/project-sync. -->\n"

func replaceSection(text, tag, replacement string) (string, error) {
	start, end := "<!-- "+tag+" -->", "<!-- /"+tag+" -->"
	if strings.Count(text, start) != 1 || strings.Count(text, end) != 1 {
		return "", fmt.Errorf("expected exactly one %s section", tag)
	}
	i := strings.Index(text, start) + len(start)
	j := strings.Index(text, end)
	if j < i {
		return "", fmt.Errorf("invalid section %s", tag)
	}
	return text[:i] + "\n" + generatedMD + replacement + text[j:], nil
}
func validateMetadata(p *Project) error {
	if err := validateEditable(p); err != nil {
		return err
	}
	if err := validateTeams(p.Org); err != nil {
		return err
	}
	if len(p.Org.Admins) == 0 {
		return fmt.Errorf("organization admins cannot be empty")
	}
	if len(p.Maintainers.Entries) != 1 {
		return fmt.Errorf("expected one CNCF project entry")
	}
	e := p.Maintainers.Entries[0]
	if e.ProjectID != "falco" || e.Org != organization {
		return fmt.Errorf("invalid CNCF project identity")
	}
	seen := set{}
	managed := 0
	for _, t := range e.Teams {
		if seen[t.Name] {
			return fmt.Errorf("duplicate roster team %s", t.Name)
		}
		seen[t.Name] = true
		if t.Managed {
			managed++
			if t.Name != "core-maintainers" || len(t.Members) == 0 {
				return fmt.Errorf("only nonempty core-maintainers may be managed")
			}
		}
		if !t.Managed && t.Name == "core-maintainers" {
			return fmt.Errorf("core-maintainers must be managed")
		}
		if len(newSet(t.Members...)) != len(t.Members) {
			return fmt.Errorf("duplicate handles in %s", t.Name)
		}
		for _, login := range t.Members {
			if !loginPattern.MatchString(login) {
				return fmt.Errorf("invalid login %q", login)
			}
		}
	}
	if managed != 1 {
		return fmt.Errorf("exactly one managed team is required")
	}
	repos := set{}
	for _, r := range p.Catalog {
		if repos[r.Name] {
			return fmt.Errorf("duplicate repository %s", r.Name)
		}
		repos[r.Name] = true
		cfg, ok := p.Org.Repos[r.Name]
		if !ok {
			return fmt.Errorf("%s is missing from org.yaml", r.Name)
		}
		if cfg.Archived != nil && *cfg.Archived {
			return fmt.Errorf("archived %s must not remain in metadata", r.Name)
		}
		if !seen[teamName(r.Name)] {
			return fmt.Errorf("%s has no roster team", r.Name)
		}
	}
	if len(seen) != len(repos)+1 {
		return fmt.Errorf("roster contains teams outside the repository catalog")
	}
	for name, cfg := range p.Org.Repos {
		if !repos[name] || cfg.Archived != nil && *cfg.Archived {
			return fmt.Errorf("repository %s is outside the active catalog", name)
		}
	}
	return nil
}

// Presubmit validates editable inputs independently of derived state. A catalog
// addition must be mergeable before the bot can create its team and roster.
func validateEditable(p *Project) error {
	if len(p.Org.Admins) == 0 || len(p.Catalog) == 0 {
		return fmt.Errorf("admins and repository catalog must not be empty")
	}
	seen, teams := set{}, set{}
	for _, r := range p.Catalog {
		if !repoPattern.MatchString(r.Name) || r.Name == "." || r.Name == ".." || seen[r.Name] {
			return fmt.Errorf("invalid or duplicate repository %q", r.Name)
		}
		seen[r.Name] = true
		team := teamName(r.Name)
		if team == "core-maintainers" || teams[team] {
			return fmt.Errorf("repository %s has a conflicting team name", r.Name)
		}
		teams[team] = true
		switch r.Scope {
		case "Core", "Ecosystem", "Infra", "Special":
		default:
			return fmt.Errorf("invalid scope %q", r.Scope)
		}
		switch r.Status {
		case "Stable", "Incubating", "Sandbox", "Deprecated":
		case "":
			if r.Scope != "Special" {
				return fmt.Errorf("%s needs a status", r.Name)
			}
		default:
			return fmt.Errorf("invalid status %q", r.Status)
		}
	}
	aliases, logins := set{}, set{}
	for login := range p.Affiliations {
		if !loginPattern.MatchString(login) || logins[strings.ToLower(login)] {
			return fmt.Errorf("invalid affiliation login %q", login)
		}
		logins.add(login)
	}
	for login, person := range p.Affiliations {
		if len(person.EmeritusAliases) > 0 && person.GitHubID <= 0 {
			return fmt.Errorf("historical aliases for %s require a verified github_id", login)
		}
		for _, alias := range person.EmeritusAliases {
			key := strings.ToLower(alias)
			if !loginPattern.MatchString(alias) || aliases[key] || logins[key] {
				return fmt.Errorf("invalid or conflicting historical alias %q", alias)
			}
			aliases.add(alias)
		}
	}
	return nil
}
func render(p *Project, dir string, write bool) ([]string, error) {
	if err := validateMetadata(p); err != nil {
		return nil, err
	}
	raw, err := os.ReadFile(filepath.Join(dir, "MAINTAINERS.md"))
	if err != nil {
		return nil, err
	}
	m := string(raw)
	all, core := set{}, set{}
	for _, team := range p.Maintainers.Entries[0].Teams {
		if team.Managed {
			core.add(team.Members...)
		} else {
			all.add(team.Members...)
		}
	}
	list := func(s set) string {
		logins := s.list()
		sort.SliceStable(logins, func(i, j int) bool { return p.Affiliations[logins[i]].Name < p.Affiliations[logins[j]].Name })
		var b strings.Builder
		for _, login := range logins {
			person, ok := p.Affiliations[login]
			if !ok {
				person = Person{Name: login, Company: "UNKNOWN"}
			}
			fmt.Fprintf(&b, "- [%s](https://github.com/%s), %s\n", escapeMD(person.Name), login, escapeMD(person.Company))
		}
		return b.String()
	}
	if m, err = replaceSection(m, "MAINTAINERS-CORE-LIST", list(core)); err != nil {
		return nil, err
	}
	if m, err = replaceSection(m, "MAINTAINERS-LIST", list(all)); err != nil {
		return nil, err
	}
	// The old clock-based banner created a diff on every successful run.
	var lines []string
	for _, line := range strings.Split(m, "\n") {
		if !strings.Contains(line, "<!-- LATEST-UPDATE -->") {
			lines = append(lines, line)
		}
	}
	m = strings.Join(lines, "\n")
	raw, err = os.ReadFile(filepath.Join(dir, "README.md"))
	if err != nil {
		return nil, err
	}
	readme := string(raw)
	colors := map[string]string{"Stable": "brightgreen", "Incubating": "orange", "Sandbox": "red", "Deprecated": "inactive"}
	for _, scope := range []string{"Core", "Ecosystem", "Infra", "Special"} {
		var table strings.Builder
		table.WriteString("| Name | Status | Description |\n| --- | --- | --- |\n")
		repos := append([]Repository(nil), p.Catalog...)
		sort.Slice(repos, func(i, j int) bool { return repos[i].Name < repos[j].Name })
		for _, repo := range repos {
			if repo.Scope != scope {
				continue
			}
			status := "*n/a*"
			if repo.Status != "" {
				status = fmt.Sprintf("[![%s](https://img.shields.io/badge/status-%s-%s?style=for-the-badge)](https://github.com/falcosecurity/evolution/blob/main/REPOSITORIES.md#%s)", repo.Status, strings.ToLower(repo.Status), colors[repo.Status], strings.ToLower(repo.Status))
			}
			description := ""
			if d := p.Org.Repos[repo.Name].Description; d != nil {
				description = *d
			}
			fmt.Fprintf(&table, "| [falcosecurity/%s](https://github.com/falcosecurity/%s) | %s | %s |\n", repo.Name, repo.Name, status, escapeMD(description))
		}
		if readme, err = replaceSection(readme, "REPOSITORY-"+strings.ToUpper(scope)+"-TABLE", table.String()); err != nil {
			return nil, err
		}
	}
	r := Result{Files: map[string][]byte{"MAINTAINERS.md": []byte(m), "README.md": []byte(readme)}}
	return applyResult(dir, r, write)
}
func escapeMD(s string) string {
	r := strings.NewReplacer("\\", "\\\\", "|", "\\|", "[", "\\[", "]", "\\]", "\r", " ", "\n", " ", "<", "&lt;", ">", "&gt;")
	return r.Replace(s)
}
