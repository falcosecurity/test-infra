package main

import (
	_ "embed"
	"fmt"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

//go:embed job-template.yaml
var jobTemplate []byte

const jobsPath = "config/jobs/oci/automation/project-sync.yaml"

func renderJobs(p *Project) (Result, error) {
	r := Result{Files: map[string][]byte{}}
	var template yaml.Node
	if err := yaml.Unmarshal(jobTemplate, &template); err != nil {
		return r, err
	}
	base := template.Content[0]
	for _, key := range []string{"spec", "extra_refs", "decoration_config"} {
		field(base, key).Anchor = "project-sync-" + strings.ReplaceAll(key, "_", "-")
	}
	if err := put(base, "name", "project-sync-reconcile"); err != nil {
		return r, err
	}
	if err := put(base, "interval", "24h"); err != nil {
		return r, err
	}
	root := mapping()
	root.Content = append(root.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "periodics"}, &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: []*yaml.Node{base}})
	posts := ensureMap(root, "postsubmits")
	repos := append([]Repository(nil), p.Catalog...)
	sort.Slice(repos, func(i, j int) bool { return repos[i].Name < repos[j].Name })
	for _, repo := range repos {
		cfg, ok := p.Org.Repos[repo.Name]
		if !ok || cfg.DefaultBranch == nil || *cfg.DefaultBranch == "" {
			return r, fmt.Errorf("%s needs an explicit default_branch in org.yaml to generate triggers", repo.Name)
		}
		n := mapping()
		for i := 0; i < len(base.Content); i += 2 {
			key, value := base.Content[i], base.Content[i+1]
			if key.Value == "interval" {
				continue
			}
			if value.Anchor != "" {
				value = &yaml.Node{Kind: yaml.AliasNode, Value: value.Anchor, Alias: value}
			}
			n.Content = append(n.Content, key, value)
		}
		if err := put(n, "name", "project-sync-"+strings.TrimPrefix(repo.Name, ".")); err != nil {
			return r, err
		}
		if err := put(n, "branches", []string{"^" + regexp.QuoteMeta(*cfg.DefaultBranch) + "$"}); err != nil {
			return r, err
		}
		if err := put(n, "run_if_changed", `(^|/)OWNERS(_ALIASES)?$`); err != nil {
			return r, err
		}
		if repo.Name == ".project" {
			if err := put(n, "run_if_changed", `(^|/)OWNERS(_ALIASES)?$|^config/(org|repository|affiliations)\.yaml$|^maintainers\.yaml$`); err != nil {
				return r, err
			}
		}
		posts.Content = append(posts.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: organization + "/" + repo.Name}, &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq", Content: []*yaml.Node{n}})
	}
	b, err := yamlBytes(root, "# AUTOGENERATED - DO NOT EDIT.\n# Source: .project/config/repository.yaml and config/org.yaml.\n# Generator: tools/project-sync jobs; runtime template: tools/project-sync/job-template.yaml.")
	r.Files[jobsPath] = b
	return r, err
}
