const catalogComment = "# AUTOMATICALLY UPDATED, but editable.\n# Edit name, scope, and status here. Descriptions belong in config/org.yaml.\n# Archived repositories are removed by project-sync. Removing an active entry does not archive it."
const orgComment = "AUTOMATICALLY UPDATED, but editable.\nEdit admins, organization settings, repository descriptions/settings, team settings/permissions,\nand purpose-specific teams manually. Organization members and repository/core team membership\nare generated from OWNERS. Archived repositories and their references are removed.\nSource and implementation: falcosecurity/test-infra/tools/project-sync."
const affiliationComment = "# AUTOMATICALLY UPDATED, but editable.\n# Edit name and company for each GitHub login. New eligible accounts receive placeholders.\n# Entries with no active-repository OWNERS reference and no organization admin role are removed."
const rosterComment = "# AUTOGENERATED - DO NOT EDIT.\n# Source: active repositories' OWNERS and config/repository.yaml.\n# Only core-maintainers is managed by CNCF. Other teams list approvers only;\n# GitHub repository teams in config/org.yaml also include reviewers."

type Result struct {
	Files   map[string][]byte
	Core    set
	Catalog []Repository
	Summary []string
}

func reconcile(p *Project, snapshot Snapshot) (Result, error) {
	r := Result{Files: map[string][]byte{}, Core: set{}}
	if err := validateEditable(p); err != nil {
		return r, err
	}
	registered := set{}
	for _, repo := range p.Catalog {
		if repo.Name == "" || registered[repo.Name] {
			return r, fmt.Errorf("empty or duplicate repository %q", repo.Name)
		}
		registered[repo.Name] = true
		s, ok := snapshot.Repositories[repo.Name]
		if !ok {
			return r, fmt.Errorf("missing snapshot for %s", repo.Name)
		}
		if s.Archived {
			continue
		}
		switch repo.Scope {
		case "Core", "Ecosystem", "Infra", "Special":
		default:
			return r, fmt.Errorf("%s has invalid scope %q", repo.Name, repo.Scope)
		}
		if repo.Scope != "Special" && repo.Status == "" {
			return r, fmt.Errorf("%s needs a status", repo.Name)
		}
		switch repo.Status {
		case "", "Stable", "Incubating", "Sandbox", "Deprecated":
		default:
			return r, fmt.Errorf("invalid status %q", repo.Status)
		}
		r.Catalog = append(r.Catalog, repo)
	}
	for name, s := range snapshot.Repositories {
		if !s.Archived && !registered[name] {
			return r, fmt.Errorf("active repository %s is not registered in config/repository.yaml", name)
		}
	}
	if len(r.Catalog) == 0 {
		return r, fmt.Errorf("empty active catalog")
	}
	sort.Slice(r.Catalog, func(i, j int) bool { return r.Catalog[i].Name < r.Catalog[j].Name })
	owners := map[string]Ownership{}
	eligible := set{}
	for _, repo := range r.Catalog {
		o, err := parseOwnership(snapshot.Repositories[repo.Name])
		if err != nil {
			return r, err
		}
		if snapshot.Accounts != nil {
			var warnings []string
			o, warnings, err = validateAccounts(o, snapshot.Accounts)
			if err != nil {
				return r, fmt.Errorf("%s: %w", repo.Name, err)
			}
			for _, warning := range warnings {
				r.Summary = append(r.Summary, repo.Name+": "+warning)
			}
		}
		owners[repo.Name] = o
		eligible.union(o.Approvers)
		eligible.union(o.Reviewers)
		eligible.union(o.Emeritus)
		if repo.Scope == "Core" {
			r.Core.union(o.RootApprovers)
		}
	}
	if len(r.Core) == 0 {
		return r, fmt.Errorf("no core maintainers; refusing reconciliation")
	}
	admins := newSet(p.Org.Admins...)
	orgNode := field(field(p.OrgDocument, "orgs"), organization)
	p.OrgDocument.Content[0].HeadComment = ""
	p.OrgDocument.Content[0].Content[0].HeadComment = orgComment
	if err := put(orgNode, "members", eligible.minus(admins).list()); err != nil {
		return r, err
	}
	active := set{}
	for _, repo := range r.Catalog {
		if teamName(repo.Name) == "core-maintainers" {
			return r, fmt.Errorf("repository %s conflicts with the reserved core-maintainers team", repo.Name)
		}
		active[repo.Name] = true
	}
	repos := ensureMap(orgNode, "repos")
	for name, cfg := range p.Org.Repos {
		if cfg.Archived != nil && *cfg.Archived {
			if active[name] {
				return r, fmt.Errorf("%s is configured archived but still active on GitHub; archive it before removing metadata", name)
			}
		}
		if !active[name] {
			drop(repos, name)
		}
	}
	for _, repo := range r.Catalog {
		n := ensureMap(repos, repo.Name)
		// Record the observed default branch once. Explicit edits remain authoritative
		// and cause Peribolos and the generated postsubmit triggers to converge.
		if field(n, "default_branch") == nil {
			if err := put(n, "default_branch", snapshot.Repositories[repo.Name].DefaultBranch); err != nil {
				return r, err
			}
		}
		if _, exists := p.Org.Repos[repo.Name]; !exists {
			defaults := map[string]any{"description": "", "allow_merge_commit": false, "allow_squash_merge": false, "allow_rebase_merge": true, "has_wiki": false}
			for _, k := range []string{"description", "allow_merge_commit", "allow_squash_merge", "allow_rebase_merge", "has_wiki"} {
				v := defaults[k]
				if err := put(n, k, v); err != nil {
					return r, err
				}
			}
			if err := put(n, "default_branch", snapshot.Repositories[repo.Name].DefaultBranch); err != nil {
				return r, err
			}
		}
	}
	teams := ensureMap(orgNode, "teams")
	// Retired repository teams and references are configuration, not history.
	for repo := range p.Org.Repos {
		if !active[repo] {
			drop(teams, teamName(repo))
		}
	}
	pruneRepoReferences(teams, active)
	entry := MaintainerEntry{ProjectID: "falco", Org: organization, Teams: []Team{{Name: "core-maintainers", Managed: true, Members: r.Core.list()}}}
	for _, repo := range r.Catalog {
		o := owners[repo.Name]
		all := newSet(o.Approvers.list()...)
		all.union(o.Reviewers)
		t := ensureMap(teams, teamName(repo.Name))
		if field(t, "privacy") == nil {
			if err := put(t, "privacy", "closed"); err != nil {
				return r, err
			}
		}
		if field(t, "description") == nil {
			if err := put(t, "description", "maintainers of falcosecurity/"+repo.Name); err != nil {
				return r, err
			}
		}
		permissions := ensureMap(t, "repos")
		if field(permissions, repo.Name) == nil {
			if err := put(permissions, repo.Name, "maintain"); err != nil {
				return r, err
			}
		}
		if err := setTeamPeople(t, all, admins); err != nil {
			return r, err
		}
		entry.Teams = append(entry.Teams, Team{Name: teamName(repo.Name), Managed: false, Members: o.Approvers.list()})
	}
	coreTeam := ensureMap(teams, "core-maintainers")
	if field(coreTeam, "privacy") == nil {
		if err := put(coreTeam, "privacy", "closed"); err != nil {
			return r, err
		}
	}
	if err := setTeamPeople(coreTeam, r.Core, admins); err != nil {
		return r, err
	}
	orgBytes, err := yamlBytes(p.OrgDocument, "")
	if err != nil {
		return r, err
	}
	var cfg proworg.FullConfig
	if err = prowyaml.UnmarshalStrict(orgBytes, &cfg); err != nil {
		return r, err
	}
	if err = validateTeams(cfg.Orgs[organization]); err != nil {
		return r, err
	}
	r.Files["config/org.yaml"] = orgBytes
	r.Files["config/repository.yaml"], err = yamlBytes(r.Catalog, catalogComment)
	if err != nil {
		return r, err
	}
	r.Files["maintainers.yaml"], err = yamlBytes(Maintainers{Entries: []MaintainerEntry{entry}}, rosterComment)
	if err != nil {
		return r, err
	}
	people := map[string]Person{}
	eligible.union(admins)
	for login := range eligible {
		person := Person{Name: login, Company: "UNKNOWN"}
		for key, value := range p.Affiliations {
			if strings.EqualFold(key, login) {
				person = value
				break
			}
		}
		people[login] = person
	}
	r.Files["config/affiliations.yaml"], err = yamlBytes(people, affiliationComment)
	if err != nil {
		return r, err
	}
	previous := newSet(p.Org.Members...)
	previous.union(admins)
	r.Summary = append(r.Summary, "Organization additions: "+strings.Join(eligible.minus(previous).list(), ", "))
	r.Summary = append(r.Summary, "Organization removals: "+strings.Join(previous.minus(eligible).list(), ", "))
	oldCore := set{}
	if t, ok := p.Org.Teams["core-maintainers"]; ok {
		oldCore.add(t.Members...)
		oldCore.add(t.Maintainers...)
	}
	r.Summary = append(r.Summary, "Core additions: "+strings.Join(r.Core.minus(oldCore).list(), ", "), "Core removals: "+strings.Join(oldCore.minus(r.Core).list(), ", "))
	return r, nil
}

func validateAccounts(o Ownership, accounts map[string]Account) (Ownership, []string, error) {
	var warnings []string
	resolve := func(people set, emeritus bool) (set, error) {
		out := set{}
		for _, login := range people.list() {
			a, ok := accounts[login]
			if !ok {
				return nil, fmt.Errorf("snapshot lacks account verification for %s", login)
			}
			if a.Type != "User" || a.ID <= 0 || !loginPattern.MatchString(a.Login) {
				if !emeritus {
					return nil, fmt.Errorf("active owner %s is not a valid GitHub user", login)
				}
				warnings = append(warnings, "ignored invalid emeritus account "+login+" (historical OWNERS entry preserved)")
				continue
			}
			out.add(a.Login)
		}
		return out, nil
	}
	var err error
	if o.Approvers, err = resolve(o.Approvers, false); err != nil {
		return o, warnings, err
	}
	if o.Reviewers, err = resolve(o.Reviewers, false); err != nil {
		return o, warnings, err
	}
	if o.RootApprovers, err = resolve(o.RootApprovers, false); err != nil {
		return o, warnings, err
	}
	o.Emeritus, err = resolve(o.Emeritus, true)
	return o, warnings, err
}

func setTeamPeople(n *yaml.Node, people, admins set) error {
	maintainers := people.minus(people.minus(admins))
	if err := put(n, "maintainers", maintainers.list()); err != nil {
		return err
	}
	return put(n, "members", people.minus(admins).list())
}
func pruneRepoReferences(teams *yaml.Node, active set) {
	for i := 1; i < len(teams.Content); i += 2 {
		t := teams.Content[i]
		if repos := field(t, "repos"); repos != nil {
			var remove []string
			for j := 0; j < len(repos.Content); j += 2 {
				if !active[repos.Content[j].Value] {
					remove = append(remove, repos.Content[j].Value)
				}
			}
			for _, name := range remove {
				drop(repos, name)
			}
		}
		if children := field(t, "teams"); children != nil {
			pruneRepoReferences(children, active)
		}
	}
}
func validateTeams(cfg proworg.Config) error {
	people := newSet(cfg.Members...)
	admins := newSet(cfg.Admins...)
	for login := range people {
		if admins[login] {
			return fmt.Errorf("%s appears in both members and admins", login)
		}
	}
	people.union(admins)
	var check func(map[string]proworg.Team) error
	check = func(teams map[string]proworg.Team) error {
		for name, t := range teams {
			for _, login := range append(t.Members, t.Maintainers...) {
				if !people[strings.ToLower(login)] {
					return fmt.Errorf("team %s retains ineligible org member %s; correct its manually maintained configuration", name, login)
				}
			}
			if err := check(t.Children); err != nil {
				return err
			}
		}
		return nil
	}
	return check(cfg.Teams)
}
func applyResult(dir string, r Result, write bool) ([]string, error) {
	var changed []string
	names := make([]string, 0, len(r.Files))
	for n := range r.Files {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		yes, err := writeChanged(filepath.Join(dir, n), r.Files[n], write)
		if err != nil {
			return nil, err
		}
		if yes {
			changed = append(changed, n)
		}
	}
	return changed, nil
}
